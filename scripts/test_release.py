class ASubject(unittest.TestCase):
    def test_is_the_title_its_type_and_the_number_the_queue_appended(self):
        t = R.read_subject("fix(web): a toast is never dropped (#212)")
        self.assertEqual(t, R.Title(212, "fix(web): a toast is never dropped", "fix", False))

    def test_a_bang_after_the_type_is_breaking(self):
        self.assertTrue(R.read_subject("feat(engine)!: seeds deal differently (#3)").breaking)
        self.assertTrue(R.read_subject("refactor!: one stream (#4)").breaking)
        self.assertFalse(R.read_subject("feat: a thing! (#5)").breaking)

    def test_a_type_pr_checks_does_not_accept_is_no_type(self):
        for s in ("PATCH: a sound fades up (#230)", "CI: read the channel (#125)", "A toast has its turn (#220)", 'Revert "feat: x" (#9)', "PATCH!: loud (#1)"):
            t = R.read_subject(s)
            self.assertEqual((t.type, t.breaking), (None, False), s)

    def test_only_the_number_at_the_end_is_the_prs(self):
        t = R.read_subject("PATCH's specs; #120, #127 fixed and back (#168)")
        self.assertEqual((t.number, t.title), (168, "PATCH's specs; #120, #127 fixed and back"))
        self.assertEqual(R.read_subject("fix: pushed by hand").number, None)


class TheVersion(unittest.TestCase):
    def level(self, *subjects, major=0):
        return R.level_for(titles(*subjects), major)[0]

    def test_a_feat_is_minor_a_fix_or_perf_a_patch(self):
        self.assertEqual(self.level("fix: a (#1)", "feat(web): b (#2)", "docs: c (#3)"), "minor")
        self.assertEqual(self.level("fix: a (#1)", "docs: c (#3)"), "patch")
        self.assertEqual(self.level("perf(web): a (#1)"), "patch")

    def test_a_breaking_change_moves_the_minor_while_the_major_is_0(self):
        self.assertEqual(self.level("fix!: a (#1)"), "minor")
        self.assertEqual(self.level("fix!: a (#1)", major=1), "major")
        self.assertEqual(self.level("feat: a (#1)", major=1), "minor")

    def test_anything_else_alone_is_a_patch_and_says_so(self):
        level, why = R.level_for(titles("docs: a (#1)", "PATCH: b (#2)", "ci: c (#3)"), 0)
        self.assertEqual(level, "patch")
        self.assertIn("no feat, fix, perf or breaking", why)

    def test_a_bump_resets_the_numbers_below_it(self):
        self.assertEqual(R.bumped("1.4.2", "major"), "2.0.0")
        self.assertEqual(R.bumped("1.4.2", "minor"), "1.5.0")
        self.assertEqual(R.bumped("1.4.2", "patch"), "1.4.3")
        self.assertEqual(R.bumped("0.2.0", "minor"), "0.3.0")

    def test_the_last_tag_is_the_highest_release_by_number(self):
        tags = ["v0.9.0", "v0.10.0", "v0.2.0", "v1.0.0-rc1", "vfoo", "0.11.0", "v0.12"]
        self.assertEqual(R.last_tag(tags), "v0.10.0")
        self.assertIsNone(R.last_tag(["latest", "nightly"]))

    def test_counts_go_by_type_then_the_untyped(self):
        got = R.counts(titles("PATCH: x (#1)", "fix: a (#2)", "feat: b (#3)", "fix: c (#4)", "release: 0.2.0 (#5)"))
        self.assertEqual(got, [("feat", 1), ("fix", 2), ("release", 1), ("without a type", 1)])


class TheDecision(unittest.TestCase):
    FEAT = titles("feat(web): a (#10)", "fix: b (#11)")

    def test_the_titles_since_the_last_tag_pick_the_version(self):
        plan = R.decide("v0.2.0", "0.2.0", None, self.FEAT)
        self.assertEqual((plan.version, plan.computed, plan.level, plan.folded), ("0.3.0", "0.3.0", "minor", False))

    def test_a_version_asked_for_wins_when_it_is_above_the_last(self):
        plan = R.decide("v0.2.0", "0.2.0", None, self.FEAT, "1.0.0")
        self.assertEqual((plan.version, plan.computed), ("1.0.0", "0.3.0"))
        for asked in ("0.2.0", "0.1.9"):
            with self.assertRaisesRegex(R.Refused, "not above the last release, v0.2.0"):
                R.decide("v0.2.0", "0.2.0", None, self.FEAT, asked)
        with self.assertRaisesRegex(R.Refused, "not a version"):
            R.decide("v0.2.0", "0.2.0", None, self.FEAT, "v0.3.0")

    def test_nothing_merged_is_refused(self):
        with self.assertRaisesRegex(R.Refused, "nothing has merged since v0.2.0"):
            R.decide("v0.2.0", "0.2.0", None, [])

    def test_a_workspace_bumped_by_hand_is_refused(self):
        with self.assertRaisesRegex(R.Refused, "says 0.2.5 and the last tag is v0.2.0"):
            R.decide("v0.2.0", "0.2.5", None, self.FEAT)

    def test_a_release_prepared_and_not_tagged_is_folded_into(self):
        plan = R.decide("v0.2.0", "0.2.1", "0.2.1", self.FEAT)
        self.assertEqual((plan.version, plan.folded, plan.computed), ("0.2.1", True, "0.3.0"))
        self.assertEqual(R.decide("v0.2.0", "0.2.1", "0.2.1", self.FEAT, "0.2.1").version, "0.2.1")
        with self.assertRaisesRegex(R.Refused, "0.2.1 is prepared and not tagged"):
            R.decide("v0.2.0", "0.2.1", "0.2.1", self.FEAT, "0.3.0")
        with self.assertRaisesRegex(R.Refused, r"untagged, and Cargo.toml says 0.2.0"):
            R.decide("v0.2.0", "0.2.0", "0.2.1", self.FEAT)

    def test_with_no_tag_yet_the_first_is_the_workspaces_version(self):
        plan = R.decide(None, "0.1.0", None, self.FEAT)
        self.assertEqual((plan.version, plan.level), ("0.1.0", "first"))

    def test_the_section_under_unreleased_is_pending_only_untagged(self):
        self.assertEqual(R.pending_section(CHANGELOG, lambda v: False), "0.3.0")
        self.assertIsNone(R.pending_section(CHANGELOG, lambda v: v == "0.3.0"))
        released = CHANGELOG.replace("## [0.3.0] - 2026-10-06\n\nThe release, in a paragraph.\n\n### Fixed: a thing\n\n- **It works.**\n\n", "")
        self.assertIsNone(R.pending_section(released, lambda v: v == "0.2.0"))


