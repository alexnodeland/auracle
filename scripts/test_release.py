class TheNotes(unittest.TestCase):
    def test_every_type_pr_checks_accepts_has_one_group_or_is_left_out(self):
        grouped = [k for _, kinds in R.GROUPS for k in kinds] + list(R.LEFT_OUT)
        self.assertEqual(sorted(grouped), sorted(P.TYPES))

    def test_by_type_oldest_first_the_release_pr_left_out(self):
        newest_first = [
            R.read_subject("release: 0.3.0 (#9)"),
            R.read_subject("fix(web): second fix (#8)"),
            R.read_subject("The old style of title (#7)"),
            R.read_subject("tests: one (#6)"),
            R.read_subject("feat!: the big one (#5)"),
            R.read_subject("test: two (#4)"),
            R.read_subject("fix: first fix (#3)"),
            R.read_subject("docs: pushed by hand", "A Person"),
        ]
        who = {8: "ann", 7: "bob", 6: "ann", 5: "cy", 4: "dependabot[bot]", 3: "bob"}
        text = R.render(newest_first, who, "v0.2.0")
        self.assertEqual(
            text,
            "## Merged since v0.2.0\n\n"
            "7 pull requests, by type. Contributors: A Person, @bob, @dependabot[bot], @cy, @ann.\n\n"
            "### Features\n\n- feat!: the big one (#5) by @cy\n\n"
            "### Fixes\n\n- fix: first fix (#3) by @bob\n- fix(web): second fix (#8) by @ann\n\n"
            "### Documentation\n\n- docs: pushed by hand by A Person\n\n"
            "### Tests\n\n- test: two (#4) by @dependabot[bot]\n- tests: one (#6) by @ann\n\n"
            "### Without a type\n\n- The old style of title (#7) by @bob\n",
        )
        self.assertNotIn("## [", text)

    def test_the_authors_come_a_page_at_a_time_until_below_the_lowest_wanted(self):
        api = Api(250)
        got = R.authors([250, 160, 130], api)
        self.assertEqual(got, {250: "user1", 160: "user1", 130: "user1"})
        self.assertEqual(len(api.calls), 2)
        self.assertTrue(all("state=closed" in c and "direction=desc" in c for c in api.calls))

    def test_one_the_pages_never_showed_is_asked_for_alone(self):
        # 130 isn't among the closed PRs' pages (a PR that was reopened, say):
        # the third page reaches below it, so the fourth is never read, and
        # 130 is asked for on its own.
        api = Api(350, missing={130})
        got = R.authors([300, 130], api)
