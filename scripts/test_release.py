def git_env():
    env = {k: v for k, v in os.environ.items() if not k.startswith("GIT_")}
    env.update(GIT_CONFIG_GLOBAL=os.devnull, GIT_CONFIG_NOSYSTEM="1", GIT_CEILING_DIRECTORIES=str(TMP))
    return env


class Tree:
    """A throwaway workspace: two crates, a lock, a changelog at 0.3.0 and
    changelog.d/ with its README; with `git=True`, a scratch repo too."""

    def __init__(self, git=False):
        self.git_ = git

    def __enter__(self):
        self.root = pathlib.Path(tempfile.mkdtemp(prefix="release-", dir=TMP))
        self.write("Cargo.toml", CARGO)
        self.write("crates/auracle-a/Cargo.toml", CRATE_A)
        self.write("crates/auracle-b/Cargo.toml", CRATE_B)
        self.write("Cargo.lock", LOCK)
        self.write("CHANGELOG.md", CHANGELOG)
        self.write("changelog.d/README.md", "# changelog.d\n")
        if self.git_:
            self.git("init", "-q", "-b", "main", ".")
        return self

    def __exit__(self, *exc):
        shutil.rmtree(self.root)

    def write(self, rel, text):
        p = self.root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")

    def text(self, rel):
        return (self.root / rel).read_text(encoding="utf-8")

    def git(self, *args):
        ident = ["-c", "user.name=Release Test", "-c", "user.email=release-test@example.invalid", "-c", "commit.gpgsign=false", "-c", "tag.gpgsign=false"]
        subprocess.run(["git", *ident, *args], cwd=self.root, env=git_env(), check=True, capture_output=True)

    def commit(self, subject):
        self.git("add", "-A")
        self.git("commit", "-q", "--allow-empty", "-m", subject)

    def run(self, *argv, get=None):
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            code = R.main(list(argv), self.root, get or refuse_network)
        return code, out.getvalue(), err.getvalue()


def refuse_network(url):
    raise AssertionError(f"no test reaches the network: {url}")


def titles(*subjects):
    return [R.read_subject(s) for s in subjects]


class Api:
    """The closed PRs, numbered 1 to `top`, newest first a page at a time,
    each by `who(n)`; it counts the calls."""

    def __init__(self, top, who=lambda n: {"login": f"user{n % 3}"}, missing=()):
        self.top, self.who, self.missing, self.calls = top, who, set(missing), []

    def __call__(self, url):
        self.calls.append(url)
        if "/pulls/" in url:
            n = int(url.rsplit("/", 1)[1])
            return {"number": n, "user": self.who(n)}
        page = int(url.rsplit("page=", 1)[1])
        numbers = [n for n in range(self.top, 0, -1) if n not in self.missing]
        chunk = numbers[(page - 1) * R.PAGE : page * R.PAGE]
        return [{"number": n, "user": self.who(n)} for n in chunk]


