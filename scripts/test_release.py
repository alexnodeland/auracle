class TheBump(unittest.TestCase):
    def test_writes_every_place_the_workspaces_version_is_and_nothing_else(self):
        with Tree() as t:
            before = {rel: t.text(rel) for rel in ("Cargo.toml", "crates/auracle-a/Cargo.toml", "crates/auracle-b/Cargo.toml", "Cargo.lock")}
            changed = R.bump(t.root, "0.3.0")
            self.assertEqual(
                [(p.rel, p.line + 1) for p in changed],
                [("Cargo.toml", 9), ("Cargo.toml", 17), ("crates/auracle-b/Cargo.toml", 6), ("Cargo.lock", 6), ("Cargo.lock", 13)],
            )
            for rel, text in before.items():
                was, now = text.split("\n"), t.text(rel).split("\n")
                moved = [i + 1 for i, (a, b) in enumerate(zip(was, now)) if a != b]
                self.assertEqual(moved, [p.line + 1 for p in changed if p.rel == rel], rel)
                for i in moved:
                    self.assertEqual(now[i - 1], was[i - 1].replace('"0.2.0"', '"0.3.0"'))
            # quiver-dsp, fugue, the commented-out line and the registry's
            # crate of the same name as a member keep 0.2.0.
            self.assertIn('quiver-dsp = "0.2.0"', t.text("Cargo.toml"))
            self.assertIn('# auracle-b = { path = "crates/auracle-b", version = "0.2.0" }', t.text("Cargo.toml"))
            self.assertIn('fugue = { version = "0.2.0"', t.text("crates/auracle-b/Cargo.toml"))
            self.assertEqual(t.text("Cargo.lock").count('version = "0.2.0"'), 2)

    def test_at_the_version_already_writes_nothing(self):
        with Tree() as t:
            R.bump(t.root, "0.3.0")
            lock = t.text("Cargo.lock")
            self.assertEqual(R.bump(t.root, "0.3.0"), [])
            self.assertEqual(t.text("Cargo.lock"), lock)

    def test_a_bump_half_made_by_hand_is_refused_and_nothing_written(self):
        with Tree() as t:
            t.write("crates/auracle-b/Cargo.toml", CRATE_B.replace('version = "0.2.0" }', 'version = "0.2.1" }', 1))
            with self.assertRaisesRegex(R.Refused, r"crates/auracle-b/Cargo.toml:6: 0.2.1, and Cargo.toml's workspace says 0.2.0"):
                R.bump(t.root, "0.3.0")
            self.assertIn('version = "0.2.0"', t.text("Cargo.toml"))
            code, _, err = t.run("bump", "v0.3.0")
            self.assertEqual(code, 1)
            self.assertIn("`v0.3.0` is not a version", err)

    def test_the_command_says_where_it_wrote(self):
        with Tree() as t:
            code, out, _ = t.run("bump", "0.3.0")
            self.assertEqual(code, 0)
            self.assertIn("Cargo.lock:13: 0.2.0 -> 0.3.0", out)
            code, out, _ = t.run("bump", "0.3.0")
            self.assertIn("at 0.3.0 already", out)


class TheManifests(unittest.TestCase):
    """Read line by line, as Cargo writes them: a TOML parser is in Python's
    library from 3.11 only, and `make dev-check` may run on macOS's 3.9."""

    def test_a_key_is_read_in_its_own_table_only(self):
        text = (
            '[workspace]\nmembers = ["crates/a", "crates/b"] # two\n\n'
            '[workspace.package] # the shared keys\nrust-version = "1.87"\nversion = "0.2.0"  # the workspace\'s\n\n'
            '[workspace.dependencies]\nserde = { version = "1" }\n\n[profile.release]\nversion = "9.9.9"\n'
        )
        self.assertEqual(R.strings(text, "workspace", "members"), ["crates/a", "crates/b"])
        self.assertEqual(R.string(text, "workspace.package", "version"), (5, "0.2.0"))
        self.assertEqual(R.workspace_version(text), "0.2.0")
        self.assertEqual(R.workspace_version(text.replace('version = "0.2.0"', 'version.workspace = true')), "")

    def test_an_array_on_several_lines_leaves_its_comments_out(self):
        text = '[workspace]\nmembers = [\n    "crates/a",\n    # "crates/old",\n    "crates/b", # the last\n]\nexclude = ["x"]\n'
        self.assertEqual(R.strings(text, "workspace", "members"), ["crates/a", "crates/b"])
        self.assertEqual(R.strings(text, "workspace", "exclude"), ["x"])
        self.assertEqual(R.strings(text, "workspace.package", "members"), [])

    def test_a_crate_with_no_name_is_refused(self):
        with Tree() as t:
            t.write("crates/auracle-b/Cargo.toml", CRATE_B.replace('name = "auracle-b"\n', ""))
            with self.assertRaisesRegex(R.Refused, r"^crates/auracle-b/Cargo.toml: no `name` under `\[package\]`$"):
                R.bump(t.root, "0.3.0")
            self.assertEqual(R.verify(t.root, "v0.2.0"), ["crates/auracle-b/Cargo.toml: no `name` under `[package]`"])


# ─── what a tag owes ─────────────────────────────────────────────────────────


class TheTag(unittest.TestCase):
    def ready(self, t):
        R.bump(t.root, "0.3.0")

    def test_a_ready_tree_owes_nothing(self):
        with Tree() as t:
            self.ready(t)
            self.assertEqual(R.verify(t.root, "v0.3.0"), [])
            code, out, _ = t.run("verify", "v0.3.0")
            self.assertEqual(code, 0)
            self.assertIn("v0.3.0: the workspace, CHANGELOG.md and changelog.d/ are ready", out)

    def test_a_name_that_is_not_a_releases_tag(self):
        with Tree() as t:
            self.ready(t)
            for tag in ("main", "0.3.0", "v0.3", "v0.3.0-"):
                self.assertEqual(R.verify(t.root, tag), [f"`{tag}` is not a release's tag: vX.Y.Z"])
            # A pre-release's tag is one: it owes the same, at its version.
            self.assertIn("Cargo.toml:9: 0.3.0, not 0.3.0-rc.1", R.verify(t.root, "v0.3.0-rc.1")[0])

    def test_the_workspace_at_another_version_names_each_place(self):
        with Tree() as t:
            wrong = R.verify(t.root, "v0.3.0")
            self.assertEqual(len(wrong), 5)
            self.assertIn("Cargo.toml:9: 0.2.0, not 0.3.0", wrong[0])
            self.assertTrue(wrong[-1].startswith("Cargo.lock:13: 0.2.0, not 0.3.0"))

    def test_no_section_or_an_empty_one_is_refused(self):
        with Tree() as t:
            self.ready(t)
            t.write("CHANGELOG.md", CHANGELOG.replace("[0.3.0]", "[0.3.1]"))
            self.assertEqual(R.verify(t.root, "v0.3.0"), ["CHANGELOG.md: no `## [0.3.0]` section: a release with no notes is not a release"])
            t.write("CHANGELOG.md", CHANGELOG.replace("[0.3.0]", "[0.3.0.1]"))
            self.assertIn("no `## [0.3.0]` section", R.verify(t.root, "v0.3.0")[0])
            t.write("CHANGELOG.md", f"# Changelog\n\n## [Unreleased]\n\n{C.NOTE}\n\n## [0.3.0] - 2026-10-06\n\n## [0.2.0] - 2026-08-04\n\n- x\n")
            self.assertEqual(R.verify(t.root, "v0.3.0"), ["CHANGELOG.md: the `## [0.3.0]` section is empty"])

    def test_an_entry_left_waiting_is_refused(self):
        with Tree() as t:
            self.ready(t)
            t.write("changelog.d/late.md", "### Fixed: late\n\n- **Merged while the release PR waited.**\n")
            code, _, err = t.run("verify", "v0.3.0")
            self.assertEqual(code, 1)
            self.assertIn("changelog.d/ still holds entries that no release notes mention: changelog.d/late.md", err)
            self.assertIn("folds them into `## [0.3.0]`", err)

    def test_its_section_is_the_one_release_yml_cuts(self):
        self.assertEqual(R.section(CHANGELOG, "0.3.0"), "The release, in a paragraph.\n\n### Fixed: a thing\n\n- **It works.**")
        self.assertEqual(R.section(CHANGELOG, "0.2.0"), "### Added: the rest\n\n- **More.**")


