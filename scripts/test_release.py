class TheHistory(unittest.TestCase):
    def history(self, t):
        """v0.1.0 on a feat, v0.1.1 on a fix and a docs change, a v0.9.0 on
        a branch main never merged, then a breaking fix and an untyped title
        waiting; the workspace at 0.1.1."""
        t.write("Cargo.toml", CARGO.replace('"0.2.0"', '"0.1.1"'))
        t.write("CHANGELOG.md", f"# Changelog\n\n## [Unreleased]\n\n{C.NOTE}\n\n## [0.1.1] - 2026-01-02\n\n- x\n")
        t.commit("feat: a (#1)")
        t.git("tag", "-a", "v0.1.0", "-m", "v0.1.0")
        t.commit("fix(web): b (#2)")
        t.commit("docs: c (#3)")
        t.git("tag", "v0.1.1")
        t.git("checkout", "-q", "-b", "side")
        t.commit("feat: never merged (#4)")
        t.git("tag", "v0.9.0")
        t.git("checkout", "-q", "main")
        t.commit("fix!: d (#5)")
        t.commit("PATCH: e (#6)")

    def test_plans_from_the_last_tag_main_has(self):
        with Tree(git=True) as t:
            self.history(t)
            out_file = t.root / "out"
            out_file.write_text("")
            body, message = t.root / "body.md", t.root / "message"
            with mock.patch.dict(os.environ, {"GITHUB_OUTPUT": str(out_file)}):
                code, out, err = t.run("plan", "--github-output", "--body", str(body), "--message", str(message))
            self.assertEqual(code, 0, err)
            self.assertIn("release: 0.2.0", out)
            self.assertIn("a minor bump from v0.1.1: 1 breaking (`!`), which moves the minor while the major is 0", out)
            self.assertIn("2 merged since v0.1.1: fix 1, without a type 1", out)
            self.assertIn("    PATCH: e (#6)", out)
            self.assertEqual(out_file.read_text(), "version=0.2.0\nprevious=v0.1.1\nfolded=false\n")
            self.assertIn("No issue: the 0.2.0 release", body.read_text())
            self.assertIn("with the 0 entries that waited", body.read_text())
            self.assertTrue(message.read_text().startswith("release: 0.2.0\n\nThe version and the changelog's section for 0.2.0"))

    def test_a_late_entry_folds_into_the_untagged_release_and_bumps_nothing(self):
        with Tree(git=True) as t:
            self.history(t)
            # The release PR for 0.2.0 merged and its tag was refused; an entry
            # merged after it.
            t.write("Cargo.toml", CARGO)
            t.write("CHANGELOG.md", f"# Changelog\n\n## [Unreleased]\n\n{C.NOTE}\n\n## [0.2.0] - 2026-02-03\n\nThe paragraph.\n\n- y\n\n## [0.1.1] - 2026-01-02\n\n- x\n")
            t.commit("release: 0.2.0 (#7)")
            t.write("changelog.d/late.md", "### Fixed: late\n\n- **Late.**\n")
            t.commit("fix: late (#8)")
            out_file, body, message = t.root / "out", t.root / "body.md", t.root / "message"
            out_file.write_text("")
            with mock.patch.dict(os.environ, {"GITHUB_OUTPUT": str(out_file)}):
                code, out, err = t.run("plan", "--github-output", "--body", str(body), "--message", str(message))
            self.assertEqual(code, 0, err)
            self.assertIn("folded into 0.2.0, prepared and not tagged", out)
            self.assertEqual(out_file.read_text(), "version=0.2.0\nprevious=v0.1.1\nfolded=true\n")
            self.assertIn("**The bump:** none. The workspace is at 0.2.0 already", body.read_text())
            self.assertIn("the one entry that waited in `changelog.d/` (now deleted), folded into the top of `## [0.2.0]`", body.read_text())
            self.assertIn("nothing is bumped", message.read_text())
            self.assertEqual(t.run("bump", "0.2.0")[1], "  the workspace is at 0.2.0 already: nothing to bump\n")

    def test_the_entries_waiting_are_counted_where_the_plan_reads(self):
        with Tree(git=True) as t:
            self.history(t)
            t.write("changelog.d/one.md", "### Fixed: one\n\n- **One.**\n")
            t.commit("fix: one (#7)")
            t.write("changelog.d/two.md", "### Fixed: two\n\n- **Two, not committed.**\n")
            body = t.root / "body.md"
            self.assertEqual(t.run("plan", "--body", str(body))[0], 0)
            self.assertIn("with the 2 entries that waited", body.read_text())
            self.assertEqual(t.run("plan", "--ref", "HEAD", "--body", str(body))[0], 0)
            self.assertIn("with the one entry that waited", body.read_text())
            self.assertEqual(t.run("plan", "--ref", "HEAD~1", "--body", str(body))[0], 0)
            self.assertIn("with the 0 entries that waited", body.read_text())

    def test_the_notes_for_a_tag_run_from_the_release_before_it(self):
        with Tree(git=True) as t:
            self.history(t)
            api = Api(6, who=lambda n: {"login": "ann"})
            code, out, err = t.run("notes", "v0.1.1", get=api)
            self.assertEqual(code, 0, err)
            self.assertTrue(out.startswith("## Merged since v0.1.0\n\n2 pull requests"))
            self.assertIn("- fix(web): b (#2) by @ann", out)
            self.assertIn("- docs: c (#3) by @ann", out)
            self.assertNotIn("(#1)", out)
            code, out, _ = t.run("notes", "--to", "HEAD", get=api)
            self.assertTrue(out.startswith("## Merged since v0.1.1\n"))
            self.assertIn("- fix!: d (#5) by @ann", out)
            self.assertNotIn("never merged", out)

    def test_a_ref_is_read_as_it_was_there(self):
        with Tree(git=True) as t:
            self.history(t)
            t.git("tag", "v0.2.0")
            # The tree moves on; the plan at the old tip reads that tip's
            # files and history, not the tree's.
            t.write("Cargo.toml", CARGO)
            t.commit("feat: f (#7)")
            code, out, err = t.run("plan", "--ref", "HEAD~1")
            self.assertEqual(code, 1)
            self.assertIn("nothing has merged since v0.2.0", err)
            code, out, err = t.run("plan")
            self.assertEqual(code, 0, err)
            self.assertIn("release: 0.3.0", out)

    def test_a_changelog_it_cannot_read_is_refused_in_one_line(self):
        with Tree(git=True) as t:
            self.history(t)
            t.write("CHANGELOG.md", t.text("CHANGELOG.md").replace("## [Unreleased]", "## Unreleased"))
            t.commit("fix: f (#7)")
            code, out, err = t.run("plan")
            self.assertEqual((code, out), (1, ""))
            self.assertEqual(err, "  CHANGELOG.md: 0 `## [Unreleased]` headings, not one\n")

    def test_notes_takes_a_tag_or_a_ref(self):
        with Tree(git=True) as t:
            self.history(t)
            with contextlib.redirect_stderr(io.StringIO()), self.assertRaises(SystemExit):
                t.run("notes")
            code, _, err = t.run("notes", "main")
            self.assertEqual(code, 1)
            self.assertIn("`main` is not a release's tag", err)


