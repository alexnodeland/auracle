class TheRealWorkspace(unittest.TestCase):
    FILES = ["Cargo.toml", "Cargo.lock"] + [str(p.relative_to(R.ROOT)) for p in sorted(R.ROOT.glob("crates/*/Cargo.toml"))]

    def test_every_place_agrees_on_one_version(self):
        found = R.places(R.ROOT)
        self.assertEqual({p.version for p in found}, {found[0].version}, found)
        self.assertEqual(found[0].rel, "Cargo.toml")

    def test_a_bump_moves_the_workspace_and_its_lock_and_nothing_else(self):
        tmp = pathlib.Path(tempfile.mkdtemp(prefix="release-real-", dir=TMP))
        try:
            for rel in self.FILES:
                (tmp / rel).parent.mkdir(parents=True, exist_ok=True)
                shutil.copy(R.ROOT / rel, tmp / rel)
            crates = R.members(tmp)
            changed = R.bump(tmp, "9.9.9")
            # The workspace's own, each pinned path dependency between its
            # crates, and each crate's entry in the lock.
            self.assertEqual(sum(1 for p in changed if p.rel == "Cargo.lock"), len(crates))
            self.assertEqual(R.verify(tmp, "v9.9.9")[:1], ["CHANGELOG.md: no `## [9.9.9]` section: a release with no notes is not a release"])
            self.assertEqual({p.version for p in R.places(tmp)}, {"9.9.9"})
            for rel in self.FILES:
                was = (R.ROOT / rel).read_text(encoding="utf-8").split("\n")
                now = (tmp / rel).read_text(encoding="utf-8").split("\n")
                moved = sum(1 for a, b in zip(was, now) if a != b)
                self.assertEqual((len(was), moved), (len(now), sum(1 for p in changed if p.rel == rel)), rel)
        finally:
            shutil.rmtree(tmp)


